type I18nContextType = {
  lang: Language;
  setLang: (lang: Language) => void;
  t: (key: string) => string;
  dir: 'rtl' | 'ltr';
  specialtyName: (specialty: Specialty | null | undefined) => string;
  specialtyDesc: (specialty: Specialty | null | undefined) => string;
};

const I18nContext = createContext<I18nContextType>({
  lang: 'ar',
  setLang: () => {},
  t: (key: string) => key,
  dir: 'rtl',
  specialtyName: (s) => s?.name || '',
  specialtyDesc: (s) => s?.description || '',
});

export function useI18n() {
  return useContext(I18nContext);
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Language>(() => {
    return (localStorage.getItem('lang') as Language) || 'ar';
  });

  const dir = lang === 'ar' ? 'rtl' : 'ltr';

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
    localStorage.setItem('lang', lang);
  }, [lang, dir]);

  const setLang = (l: Language) => setLangState(l);

  const t = (key: string) => {
    const dict = translations[lang];
    if (dict && dict[key]) return dict[key];
    return translations.ar[key] || key;
  };

  const specialtyName = (specialty: Specialty | null | undefined): string => {
    if (!specialty) return '';
    if (lang === 'en') return specialty.name_en || specialty.name;
    if (lang === 'de') return specialty.name_de || specialty.name;
    if (lang === 'ru') return specialty.name_ru || specialty.name;
    return specialty.name;
  };

  const specialtyDesc = (specialty: Specialty | null | undefined): string => {
    if (!specialty) return '';
    if (lang === 'en') return specialty.description_en || specialty.description;
    if (lang === 'de') return specialty.description_de || specialty.description;
    if (lang === 'ru') return specialty.description_ru || specialty.description;
    return specialty.description;
  };

  return (
    <I18nContext.Provider value={{ lang, setLang, t, dir, specialtyName, specialtyDesc }}>
      {children}
    </I18nContext.Provider>
  );
}
