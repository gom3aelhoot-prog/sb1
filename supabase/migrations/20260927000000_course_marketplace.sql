create or replace function public.sb1_course_free_seats(p_enrolled integer,p_lessons integer)
returns integer language sql immutable as $$
 select case when coalesce(p_enrolled,0)>50 then greatest(1,ceil(coalesce(p_enrolled,0)*0.10)::integer)
 else least(3,greatest(1,ceil(coalesce(p_lessons,1)/10.0)::integer)) end;
$$;

update public.courses
set platform_share_percent=50,specialist_share_percent=50,moderation_required=true
where platform_share_percent is null or specialist_share_percent is null;
