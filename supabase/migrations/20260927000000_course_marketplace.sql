-- SB1 course marketplace: private course chat, moderation terms, 50/50 revenue split, and free-seat allocation.
alter table if exists public.courses add column if not exists is_free boolean default false;
alter table if exists public.courses add column if not exists platform_share_percent numeric default 50;
alter table if exists public.courses add column if not exists specialist_share_percent numeric default 50;
alter table if exists public.courses add column if not exists moderation_required boolean default true;
alter table if exists public.courses add column if not exists specialist_connect_account_id text;
alter table if exists public.courses add column if not exists free_seats integer default 1;
alter table if exists public.courses add column if not exists terms_version text default 'course-v1';

create table if not exists public.course_enrollments (
 id uuid primary key default gen_random_uuid(),
 course_id uuid references public.courses(id) on delete cascade,
 user_id uuid null,
 student_name text,
 student_email text,
 payment_status text not null default 'pending',
 stripe_session_id text,
 amount numeric default 0,
 currency text default 'USD',
 created_at timestamptz not null default now(),
 unique(course_id,student_email)
);
alter table public.course_enrollments enable row level security;

create table if not exists public.course_chat_messages (
 id uuid primary key default gen_random_uuid(),
 course_id uuid references public.courses(id) on delete cascade,
 sender_id uuid null,
 sender_name text not null,
 body text not null,
 is_flagged boolean default false,
 created_at timestamptz not null default now()
);
alter table public.course_chat_messages enable row level security;

create table if not exists public.course_moderation_rules (
 id bigint generated by default as identity primary key,
 rule_key text unique not null,
 rule_text text not null,
 active boolean default true,
 created_at timestamptz not null default now()
);
